import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { scopeOf } from './options.mjs';
import { catalogVersions, UI_FRAMEWORKS } from './ui-frameworks.mjs';
import { applyPreprocessor } from './preprocessor.mjs';

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function writeJson(path, data) {
  writeFileSync(path, JSON.stringify(data, null, 2) + '\n');
}

export function writeLibConfig(root, opts) {
  const content = `import type { LibConfig } from '@internal/build';

const config: LibConfig = {
  name: '${opts.name}',
  installerName: '${opts.installer}',
  installer: { skip: [] },
  componentPrefix: '${opts.prefix}',
  cssPrefix: '${opts.cssPrefix}',
  preprocessor: '${opts.preprocessor ?? 'none'}',
  formats: ['es'],
  styles: 'inject',
};

export default config;
`;
  writeFileSync(join(root, 'lib.config.ts'), content);
}

// Mirrors renderCssPrefix in internal/build/src/contract/sync.ts so `check:contract` stays green after bootstrap.
export function writeCssPrefix(root, opts) {
  const content = `// generated by contract:sync
export const CSS_PREFIX = '${opts.cssPrefix}';
`;
  writeFileSync(join(root, 'packages/utils/src/css-prefix.ts'), content);
}

export function writeNpmrc(root, opts) {
  const scope = scopeOf(opts.name);
  const body = scope ? `${scope}:registry=${opts.registry}\n` : `registry=${opts.registry}\n`;
  writeFileSync(join(root, '.npmrc'), body);
}

export function editManifests(root, opts) {
  const ui = UI_FRAMEWORKS[opts.ui];
  const core = readJson(join(root, 'packages/core/package.json'));
  core.name = opts.name;
  core.license = opts.license;
  core.peerDependencies = { ...core.peerDependencies, ...ui.peer };
  if (opts.registry) {
    core.publishConfig = {
      ...(core.publishConfig ?? {}),
      registry: opts.registry,
      access: 'public',
    };
  }
  writeJson(join(root, 'packages/core/package.json'), core);

  const rootPkg = readJson(join(root, 'package.json'));
  rootPkg.license = opts.license;
  writeJson(join(root, 'package.json'), rootPkg);

  const workspace = readFileSync(join(root, 'pnpm-workspace.yaml'), 'utf8');
  const versions = catalogVersions();
  let next = workspace;
  for (const [pkg, spec] of Object.entries(ui.peer)) {
    const catalogLine = `  '${pkg}': ${versions[pkg] ?? spec}`;
    if (!next.includes(`'${pkg}':`) && !next.includes(`${pkg}:`)) {
      next = next.replace(/catalog:\n/, `catalog:\n${catalogLine}\n`);
    }
  }
  writeFileSync(join(root, 'pnpm-workspace.yaml'), next);

  if (Object.keys(ui.site).length) {
    for (const pkgName of ['docs', 'playground']) {
      const path = join(root, pkgName, 'package.json');
      try {
        const json = readJson(path);
        json.devDependencies = { ...json.devDependencies, ...ui.site };
        writeJson(path, json);
      } catch {
        // playground may be pruned later
      }
    }
  }

  writeFileSync(join(root, 'docs/.vitepress/theme/ui.ts'), ui.uiTs);
  try {
    writeFileSync(join(root, 'playground/src/ui.ts'), ui.uiTs);
  } catch {
    // optional
  }

  if (ui.cspell.length) {
    const cspellPath = join(root, 'cspell.json');
    const cspell = readJson(cspellPath);
    cspell.words = [...new Set([...(cspell.words ?? []), ...ui.cspell])].sort();
    writeJson(cspellPath, cspell);
  }

  const agents = readFileSync(join(root, 'AGENTS.md'), 'utf8');
  const filled = agents.replace(
    /<!-- template:company-start -->[\s\S]*?<!-- template:company-end -->/,
    `<!-- template:company-start -->
- registry: ${opts.registry}
- publish: fill in who may run \`pnpm release\`
- branch: fill in default branch policy
<!-- template:company-end -->`,
  );
  writeFileSync(join(root, 'AGENTS.md'), filled);

  writeLibConfig(root, opts);
  writeCssPrefix(root, opts);
  writeNpmrc(root, opts);
  applyPreprocessor(root, opts.preprocessor);
}
